"""Prepare owner-supplied photos, without generating/repainting image content.
Requires Pillow; e.g. pip install --target .cache/photo-tools pillow
Run: PYTHONPATH=.cache/photo-tools python3 scripts/prepare-homepage-photos.py
"""
import json
from pathlib import Path
from PIL import Image, ImageOps
ROOT = Path(__file__).resolve().parent.parent
intake = ROOT / 'photo-intake/homepage-real'
selection = json.loads((intake / 'selection.json').read_text())
output = ROOT / 'src/assets/homepage-real'
output.mkdir(parents=True, exist_ok=True)
imports = []
slides = []
for i, item in enumerate(selection['photos']):
    image = ImageOps.exif_transpose(Image.open(intake / item['source'])).convert('RGB')
    if item.get('rotate'):
        image = image.rotate(item['rotate'], expand=True)
    image.thumbnail((1600, 1600), Image.Resampling.LANCZOS)
    image.save(output / (item['id'] + '.webp'), 'WEBP', quality=82, method=6)
    imports.append(f'import photo{i} from "@/assets/homepage-real/{item["id"]}.webp";')
    fields = { 'id': item['id'], 'name': item['name'], 'width': image.width, 'height': image.height, 'position': item['desktop'], 'mobilePosition': item['mobile'] }
    row = json.dumps(fields, ensure_ascii=False)[:-1] + f', "image": photo{i}' + '}'
    slides.append('  ' + row + ',')
source = '\n'.join(imports) + '''

export type HeroSlide = {
  id: string;
  name: string;
  image: string;
  width: number;
  height: number;
  position: string;
  mobilePosition: string;
};
// Owner-supplied batch 1. Generated by scripts/prepare-homepage-photos.py.
// Selection/crops are recorded in photo-intake/homepage-real/selection.json.
export const heroSlides: HeroSlide[] = [
''' + '\n'.join(slides) + '\n];\n'
(ROOT / 'src/lib/hero-slides.ts').write_text(source)
print(f'Prepared {len(slides)} uploaded photos; wedding orientation corrected; excluded exhibition photo.')
print(f'Optimized image total: {sum(p.stat().st_size for p in output.glob("*.webp")):,} bytes')
