"""Optimise full-size batch-2 gallery photos, preserving unchanged intake originals.
Run: PYTHONPATH=.cache/photo-tools python3 scripts/prepare-gallery-photos.py
The first17 full-size images are reused from homepage-real, never re-encoded.
"""
from pathlib import Path
import json
from PIL import Image, ImageOps
root = Path(__file__).resolve().parent.parent
intake = root / 'photo-intake/homepage-real'
photos = json.loads((intake / 'circle-selection.json').read_text())['additionalPhotos']
output = root / 'src/assets/gallery-real'
output.mkdir(parents=True, exist_ok=True)
imports, rows = [], []
for i, item in enumerate(photos):
    image = ImageOps.exif_transpose(Image.open(intake / item['source'])).convert('RGB')
    image.thumbnail((1600, 1600), Image.Resampling.LANCZOS)
    image.save(output / (item['id'] + '.webp'), 'WEBP', quality=82, method=6)
    imports.append(f'import photo{i} from "@/assets/gallery-real/{item["id"]}.webp";')
    rows.append(f'  "{item["id"]}": {{ image: photo{i}, width: {image.width}, height: {image.height} }},')
(root / 'src/lib/gallery-uploaded.ts').write_text('// Generated by scripts/prepare-gallery-photos.py. Supplied images only.\n'+'\n'.join(imports)+'\nexport const galleryUploaded = {\n'+'\n'.join(rows)+'\n};\n')
print(f'Prepared{len(photos)} full-size gallery uploads; {sum(p.stat().st_size for p in output.glob("*.webp")):,} bytes')
