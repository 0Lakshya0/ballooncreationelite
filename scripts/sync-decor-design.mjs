/** Sync approved English data, shader and scoped design; never modifies the drafts. */
import fs from "node:fs";
import path from "node:path";
import postcss from "postcss";
import selectors from "postcss-selector-parser";
const dest = "src/components/balloon/decor";
const html = fs.readFileSync("mockups/final/decor-types-final.html", "utf8");
const decode = (s) =>
  s
    .replaceAll("&amp;", "&")
    .replaceAll("&quot;", '"')
    .replaceAll("&#39;", "'")
    .replaceAll("&nbsp;", " ");
const data = JSON.parse(html.match(/window\.DECOR_DATA = (\{[\s\S]*?\});\n/)[1]);
for (const m of html.matchAll(
  /<span class="nm">([^<]*)<\/span><span class="ds">([^<]*)<\/span>/g,
)) {
  const key = decode(m[1]);
  if (data[key]) data[key].desc = decode(m[2]);
}
const source = fs.readFileSync("mockups/site-ready/decorTypesData.ts", "utf8");
const types = source
  .slice(source.indexOf("export type Palette"), source.indexOf("export const CHIP_GROUPS"))
  .replace("export type Chip = {", "export type Chip = {\n  includes: string[];");
const groups = JSON.parse(
  source.match(/export const CHIP_GROUPS: ChipGroup\[\] = ([\s\S]*?);\n\n/)[1],
);
if (
  Object.keys(data).length !== 25 ||
  Object.values(data).reduce((n, c) => n + Object.keys(c.options).length, 0) !== 150
)
  throw Error("Incomplete approved catalogue");
fs.writeFileSync(
  `${dest}/decor-data.ts`,
  "// Generated from the approved English final by scripts/sync-decor-design.mjs.\n" +
    types +
    "export const CHIP_GROUPS: ChipGroup[] = " +
    JSON.stringify(groups, null, 2) +
    ";\nexport const DECOR_DATA: Record<string, Chip> = " +
    JSON.stringify(data, null, 2) +
    ";\n",
);
const css = postcss.parse(html.match(/<style>([\s\S]*?)<\/style>/)[1]);
const names = new Map();
css.walkAtRules("keyframes", (a) => {
  names.set(a.params, `bce-${a.params}`);
  a.params = `bce-${a.params}`;
});
css.walkDecls(/^animation/, (d) => {
  for (const [old, next] of names)
    d.value = d.value.replace(new RegExp(`(?<![\\w-])${old}(?![\\w-])`, "g"), next);
});
css.walkAtRules("font-face", (a) => a.remove());
css.walkRules((rule) => {
  if (rule.parent?.type === "atrule" && /keyframes$/.test(rule.parent.name)) return;
  if (rule.selector === "body.locked") {
    rule.remove();
    return;
  }
  rule.selector = selectors((root) =>
    root.each((sel) => {
      let hasRoot = false;
      sel.walk((n) => {
        if (
          (n.type === "tag" && ["html", "body"].includes(n.value)) ||
          (n.type === "pseudo" && n.value === ":root")
        ) {
          n.replaceWith(selectors.className({ value: "bce-decor" }));
          hasRoot = true;
        }
      });
      if (!hasRoot) {
        sel.prepend(selectors.combinator({ value: " " }));
        sel.prepend(selectors.className({ value: "bce-decor" }));
      }
    }),
  ).processSync(rule.selector);
});
fs.writeFileSync(
  `${dest}/approved-decor.css`,
  "/* Generated scoped approved design. Do not edit; run node scripts/sync-decor-design.mjs. */\n" +
    css
      .toString()
      .split("\n")
      .map((line) => line.trimEnd())
      .join("\n")
      .trimEnd() +
    "\n",
);
const liquid = fs.readFileSync("mockups/_english_liquid_gold.py", "utf8");
const fragment = liquid.match(/var fragment=`([\s\S]*?)`;/)[1];
fs.writeFileSync(
  `${dest}/liquid-shader.ts`,
  "// Exact approved shader; generated by scripts/sync-decor-design.mjs.\nexport const liquidFragment = " +
    JSON.stringify(fragment) +
    ";\n",
);
fs.cpSync("mockups/img", "public/decor-types", { recursive: true });
fs.cpSync("mockups/fonts", "public/decor-types/fonts", { recursive: true });
console.log(
  "Synced 25 styles / 150 options, 34 local photos, fonts, scoped CSS and approved collision shader.",
);
